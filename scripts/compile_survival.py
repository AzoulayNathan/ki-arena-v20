"""Rebuild survival data without changing any source CSV. Standard library only."""
import csv, json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
p = root / "reference-survie/catalogues"
UNIVERSES = ["DB", "HXH", "NARUTO", "ONEPIECE"]
PORTRAIT_DIRS = {
    "DB": "assets/portraits-db",
    "HXH": "assets/portraits-hxh",
    "NARUTO": "assets/portraits-naruto",
    "ONEPIECE": "assets/portraits-onepiece",
}


def rows(name):
    return list(csv.DictReader((p / name).open(encoding="utf-8-sig"), delimiter=";"))


out = {}
for universe in UNIVERSES:
    heroes = []
    for r in rows(universe + "_CARTES_SOURCE.csv"):
        sig = [
            dict(name=r[f"effet_{i}_nom"], type=r[f"effet_{i}_type"])
            for i in range(1, 6)
            if r.get(f"effet_{i}_type")
        ]
        hid = r["id"]
        heroes.append(
            dict(
                id=hid,
                name=r["nom"],
                form=r.get("version") or r.get("forme") or "",
                person=r.get("id_personnage") or hid,
                universe=universe,
                series=r.get("serie") or universe,
                attack=int(r["attaque"]),
                maxHp=int(r["pv"]),
                speed=int(r["vitesse"]),
                rarity=r["rarete"],
                signature=sig,
                portrait=f"{PORTRAIT_DIRS[universe]}/{hid}.webp",
            )
        )
    heroes.sort(key=lambda x: (x["attack"] + x["maxHp"] + x["speed"], x["id"]))
    for i, h in enumerate(heroes, 1):
        h["rank"] = i
    items = []
    for r in rows("EQUIPEMENTS_" + universe + ".csv"):
        # Personal Nen cannot be made transferable even if a source says draft=yes.
        allowed = r["classe"] in ["arme", "armure", "outil", "consommable"] and r[
            "statut_canon"
        ] not in ["NEN_PERSONNEL", "HORS_EQUIPEMENT"]
        items.append(
            dict(
                id=r["id"],
                universe=universe,
                name=r["nom"],
                category=r["classe"],
                rarity=r["rarete"],
                tier=int(r["rang_rarete"]),
                effect=r["effet_principal"],
                atk=int(r["attaque_bonus_pct"]),
                shield=int(r["armure_bouclier_pct"]),
                heal=int(r["soin_pct"]),
                draw=int(r["pioche_supplementaire"]),
                cost=int(r["cout_action_equipement"]),
                uses=int(r["utilisations_par_combat"]),
                canon=r["statut_canon"],
                owner=r["porteur_original"],
                source=r["source"],
                notes=r["notes"],
                allowed=allowed,
                draft=allowed and r["classe"] == "arme" and r["compatible_draft"] == "oui",
            )
        )
    if universe == "DB":
        items.append(
            dict(
                id="db-editorial-balise-de-riposte",
                universe="DB",
                name="Balise de riposte",
                category="outil",
                rarity="rare",
                tier=3,
                effect="counter",
                atk=0,
                shield=0,
                heal=0,
                draw=0,
                cost=1,
                uses=1,
                canon="EDITORIAL_PROPOSE",
                owner="Système KI ARENA",
                source="Création originale de gameplay V9",
                notes="Une riposte à 70 % ATQ après le premier coup reçu ; pas de chaîne ; occupe le slot arme.",
                allowed=True,
                draft=False,
            )
        )
    evo_file = p / "EVOLUTIONS_VALIDEES.csv"
    evolutions = (
        [r for r in rows("EVOLUTIONS_VALIDEES.csv") if r["univers"] == universe]
        if evo_file.exists()
        else []
    )
    out[universe] = dict(heroes=heroes, items=items, evolutions=evolutions)

(root / "src/survival/data.js").write_text(
    "/* Generated by scripts/compile_survival.py from intact CSVs. */\nexport const SURVIVAL_DATA="
    + json.dumps(out, ensure_ascii=False, separators=(",", ":"))
    + ";\n",
    encoding="utf-8",
)
print(
    "Compiled",
    {u: len(out[u]["heroes"]) for u in UNIVERSES},
    "items",
    sum(len(x["items"]) for x in out.values()),
)
